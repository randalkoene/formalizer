"""Your corrections to the classifier.

Kept in its own file, separate from config.yaml, so that re-running
`triage.py seed-config --force` can regenerate the generated config without ever
clobbering what you have taught the tool.

Nothing here touches Gmail. Teaching changes how the LOCAL cache is scored.
"""

import datetime
import os
import threading

import yaml

HERE = os.path.dirname(os.path.realpath(__file__))
CORRECTIONS_FILE = os.path.join(HERE, "corrections.yaml")

_LOCK = threading.Lock()

# What you can say about a sender or a domain.
KINDS = {
    "personal":  "real human correspondence — never bulk, never automated",
    "important": "always surface this, like a VIP",
    "bulk":      "this really is bulk — file it there",
    "ignore":    "noise I never want to see near the top",
}

HEADER = """\
# inbox-triage — your corrections to the classifier.
#
# Written by `triage.py teach` and by the browser UI's Teach buttons. Safe to
# hand-edit. This file is never regenerated by `seed-config`, so what you teach
# here survives a config rebuild.
#
# sender/domain kinds:
#   personal   real human correspondence — never bulk, never automated
#   important  always surface this, like a VIP
#   bulk       this really is bulk — file it there
#   ignore     noise I never want to see near the top
#
# lists: mailing lists and group addresses you receive via, keyed by List-Id or
# by the group address. kind: important (you read it) or ignore (you never do).
#
# my_addresses: other addresses of yours that forward into this mailbox. Mail
# addressed to them counts as addressed to you.
"""


# Mailing lists and group addresses you receive via. Kept separate from senders
# because the thing that matters is the list, not whoever posted to it.
LIST_KINDS = {
    "important": "a list or group you actually read",
    "ignore": "a list you mute — still filed in Bulk, sorted to the bottom",
}


def empty():
    return {"my_addresses": [], "senders": {}, "domains": {}, "messages": {},
            "lists": {}}


def load(path=CORRECTIONS_FILE):
    if not os.path.exists(path):
        return empty()
    with open(path) as fh:
        data = yaml.safe_load(fh) or {}
    out = empty()
    out["my_addresses"] = [a.lower() for a in (data.get("my_addresses") or [])]
    for key in ("senders", "domains", "messages", "lists"):
        for k, v in (data.get(key) or {}).items():
            out[key][str(k).lower()] = v if isinstance(v, dict) else {"kind": str(v)}
    return out


def save(data, path=CORRECTIONS_FILE):
    body = {
        "my_addresses": sorted(set(data.get("my_addresses") or [])),
        "senders": data.get("senders") or {},
        "domains": data.get("domains") or {},
        "messages": data.get("messages") or {},
        "lists": data.get("lists") or {},
    }
    tmp = path + ".tmp"
    with open(tmp, "w") as fh:
        fh.write(HEADER)
        yaml.safe_dump(body, fh, default_flow_style=False, sort_keys=True,
                       allow_unicode=True)
    os.replace(tmp, path)


def teach(target, kind, scope="sender", note=None, path=CORRECTIONS_FILE):
    """Record one correction. scope is 'sender', 'domain' or 'message'.

    kind=None removes the entry. Returns the updated corrections dict.
    """
    allowed = LIST_KINDS if scope == "list" else KINDS
    if kind is not None and scope != "message" and kind not in allowed:
        raise ValueError("unknown kind %r (choose from %s)" % (kind, ", ".join(allowed)))

    bucket = {"sender": "senders", "domain": "domains", "message": "messages",
              "list": "lists"}[scope]
    target = target.lower()

    with _LOCK:
        data = load(path)
        if kind is None:
            data[bucket].pop(target, None)
        else:
            entry = {"kind": kind, "taught": datetime.date.today().isoformat()}
            if note:
                entry["note"] = note
            data[bucket][target] = entry
        save(data, path)
        return data


def add_my_address(addr, path=CORRECTIONS_FILE, remove=False):
    with _LOCK:
        data = load(path)
        addr = addr.lower()
        addrs = set(data.get("my_addresses") or [])
        addrs.discard(addr) if remove else addrs.add(addr)
        data["my_addresses"] = sorted(addrs)
        save(data, path)
        return data


def lookup_list(corrections, keys):
    """First taught list matching any of this message's list identities."""
    table = corrections.get("lists") or {}
    for key in keys:
        hit = table.get((key or "").lower())
        if hit:
            return (key, hit.get("kind"), hit)
    return None


def lookup(corrections, from_addr, from_domain, message_id):
    """Return (scope, kind, entry) for the most specific correction, or None."""
    msg = (corrections.get("messages") or {}).get((message_id or "").lower())
    if msg:
        return ("message", msg.get("kind"), msg)
    sender = (corrections.get("senders") or {}).get((from_addr or "").lower())
    if sender:
        return ("sender", sender.get("kind"), sender)
    domain = (corrections.get("domains") or {}).get((from_domain or "").lower())
    if domain:
        return ("domain", domain.get("kind"), domain)
    return None
